import { LevelSilhouette, ArrowDefinition, ArrowDirection, GridPoint } from './types';

/**
 * Builder for verified, still 2D mazes with exactly ONE movable player arrow.
 * The maze walls and corridors are completely stationary and immovable.
 */
export function createStaticMazeLevel(
  id: number,
  name: string,
  subtitle: string,
  matrix: number[][],
  startPoint: GridPoint,
  exitPoint: GridPoint,
  initialDir: ArrowDirection = 'UP',
  timeLimit = 90,
  difficulty: 'Normal' | 'Hard' | 'Expert' | 'Insane' = 'Hard'
): LevelSilhouette {
  const height = matrix.length;
  const width = matrix[0].length;
  const obstacles: GridPoint[] = [];

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (matrix[y][x] === 2) {
        obstacles.push({ x, y });
      }
    }
  }

  // Find next adjacent open corridor cell from startPoint
  const candidateDirs: { dx: number; dy: number; dir: ArrowDirection }[] = [
    { dx: 0, dy: -1, dir: 'UP' },
    { dx: 1, dy: 0, dir: 'RIGHT' },
    { dx: 0, dy: 1, dir: 'DOWN' },
    { dx: -1, dy: 0, dir: 'LEFT' },
  ];

  let nextStep: GridPoint = { x: startPoint.x, y: startPoint.y - 1 };
  let dir = initialDir;
  for (const c of candidateDirs) {
    const nx = startPoint.x + c.dx;
    const ny = startPoint.y + c.dy;
    if (nx >= 0 && nx < width && ny >= 0 && ny < height && matrix[ny][nx] === 1) {
      nextStep = { x: nx, y: ny };
      dir = c.dir;
      break;
    }
  }

  const targetArrow: ArrowDefinition = {
    id: `main_player_arrow_${id}`,
    points: [
      { x: startPoint.x, y: startPoint.y },
      { x: nextStep.x, y: nextStep.y },
    ],
    direction: dir,
  };

  return {
    id,
    name,
    subtitle,
    shapeType: 'maze',
    gridWidth: width,
    gridHeight: height,
    arrows: [targetArrow], // EXACTLY ONE MOVABLE ARROW
    obstacles,
    gridMatrix: matrix,
    startPoint,
    exitPoint,
    isSingleTargetMaze: true,
    timeLimit,
    difficulty,
  };
}

